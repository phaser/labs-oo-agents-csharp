using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Nooa.Generators.Models;

namespace Nooa.Generators;

/// <summary>Writes the C# source for one agent class.</summary>
internal static class SourceEmitter
{
    private const string _header = "// <auto-generated/>\n#nullable enable\n";

    public static string EmitType(TypeModel type, IReadOnlyList<MethodModel> methods)
    {
        var w = new CodeWriter();
        w.Raw(_header);
        if (type.Namespace is not null)
        {
            w.Line("namespace " + type.Namespace + ";");
            w.Line();
        }

        foreach (var container in type.Containers)
        {
            w.Line("partial " + container.Keyword + " " + container.Name);
            w.Open();
        }

        w.Line("partial " + type.Keyword + " " + type.Name);
        w.Open();

        var ordered = methods.OrderBy(m => m.Signature + m.Name, System.StringComparer.Ordinal).ToList();
        var funcType = "global::System.Func<" + type.Name + ", string>";
        for (var i = 0; i < ordered.Count; i++)
        {
            if (ordered[i].Prompt is { HasPlaceholders: true } prompt)
            {
                w.Line("private static readonly " + funcType + " __NooaPrompt" + i + " = " + PromptLambda(prompt) + ";");
                w.Line();
            }
        }

        if (type.SystemPrompt is { HasPlaceholders: true } systemPrompt)
        {
            w.Line("private static readonly " + funcType + " __NooaSystemPrompt = " + PromptLambda(systemPrompt) + ";");
            w.Line();
        }

        for (var i = 0; i < ordered.Count; i++)
        {
            EmitMethod(w, ordered[i], i);
            w.Line();
        }

        EmitRegister(w, type);
        w.Line();
        EmitDocProvider(w, type);

        w.Close();
        foreach (var unused in type.Containers)
        {
            w.Close();
        }

        return w.ToString();
    }

    public static string EmitRegistration(string assemblyName, IEnumerable<TypeModel> types)
    {
        var w = new CodeWriter();
        w.Raw(_header);
        w.Line("internal static class __NooaModuleInitializer_" + Sanitize(assemblyName));
        w.Open();
        w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        w.Line("internal static void Register()");
        w.Open();
        foreach (var type in types.OrderBy(t => t.Key, System.StringComparer.Ordinal))
        {
            w.Line(type.Key + ".__NooaRegister();");
        }

        w.Close();
        w.Close();
        return w.ToString();
    }

    public static string HintName(TypeModel type) => Sanitize(type.Key) + ".Nooa.g.cs";

    private static string Sanitize(string text)
    {
        var builder = new StringBuilder();
        foreach (var c in text)
        {
            builder.Append(char.IsLetterOrDigit(c) ? c : '_');
        }

        return builder.ToString();
    }

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

    private static string PromptLambda(PromptModel prompt)
    {
        var arguments = string.Concat(prompt.Arguments.Select(a => ", (object?)" + a));
        return "static a => global::System.String.Format(global::System.Globalization.CultureInfo.InvariantCulture, "
            + Literal(prompt.Value) + arguments + ")";
    }

    private static void EmitMethod(CodeWriter w, MethodModel m, int index)
    {
        var parameters = string.Join(", ", m.Parameters.Select(p => p.DeclaredType + " " + p.Name));
        var modifiers = m.Modifiers.Length > 0 ? m.Modifiers + " " : string.Empty;
        w.Line(modifiers + "async partial " + m.ReturnType + " " + m.Name + "(" + parameters + ")");
        w.Open();
        w.Line("var __call = new global::Nooa.Strategies.CurrentCall");
        w.Open();
        w.Line("MethodName = " + Literal(m.Name) + ",");
        w.Line("Signature = " + Literal(m.Signature) + ",");
        if (m.Prompt is { } prompt)
        {
            w.Line("Docstring = " + (prompt.HasPlaceholders ? "__NooaPrompt" + index + "(this)" : Literal(prompt.Value)) + ",");
        }

        if (m.Arguments.Count > 0)
        {
            w.Line("Arguments = new global::Nooa.Strategies.CallArgument[]");
            w.Open();
            foreach (var p in m.Arguments)
            {
                w.Line("new(" + Literal(p.Name.TrimStart('@')) + ", typeof(" + p.TypeOf + "), " + p.Name + "),");
            }

            w.Close(",");
        }

        if (m.ResultTypeOf is not null)
        {
            w.Line("ReturnType = typeof(" + m.ResultTypeOf + "),");
        }

        if (m.StrategyTypeOf is not null)
        {
            w.Line("StrategyType = typeof(" + m.StrategyTypeOf + "),");
        }

        w.Close(";");
        var token = m.CancellationToken ?? "global::System.Threading.CancellationToken.None";
        var target = "((global::Nooa.IAgenticTarget)this).InvokeAgenticAsync" + (m.ResultType is not null ? "<" + m.ResultType + ">" : string.Empty);
        w.Line((m.IsAwaitableWithResult ? "return " : string.Empty) + "await " + target + "(__call, " + token + ");");
        w.Close();
    }

    private static void EmitRegister(CodeWriter w, TypeModel type)
    {
        w.Line("internal static void __NooaRegister()");
        w.Open();
        w.Line("global::Nooa.Agentdoc.AgentDocProviders.Register(new __NooaDocProvider());");
        var llm = type.Llm is null ? "null" : Literal(type.Llm);
        string prompt;
        if (type.SystemPrompt is null)
        {
            prompt = "null";
        }
        else if (type.SystemPrompt.HasPlaceholders)
        {
            prompt = "static o => __NooaSystemPrompt((" + type.Name + ")o)";
        }
        else
        {
            prompt = "static _ => " + Literal(type.SystemPrompt.Value);
        }

        w.Line("global::Nooa.AgentMetadataRegistry.Register(new global::Nooa.AgentMetadata(typeof(" + type.Name + "), " + llm + ", " + prompt + "));");
        w.Close();
    }

    private static void EmitDocProvider(CodeWriter w, TypeModel type)
    {
        var self = "typeof(" + type.Name + ")";
        w.Line("private sealed class __NooaDocProvider : global::Nooa.Agentdoc.IAgentDocProvider");
        w.Open();
        w.Line("private const global::System.Reflection.BindingFlags Flags = global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.NonPublic | global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.Static | global::System.Reflection.BindingFlags.DeclaredOnly;");
        w.Line("private readonly global::System.Collections.Generic.Dictionary<int, string> _summaries = new();");
        w.Line("private readonly global::System.Collections.Generic.Dictionary<(int Token, int Position), string> _parameters = new();");
        w.Line();
        w.Line("public __NooaDocProvider()");
        w.Open();
        if (type.TypeDoc is not null)
        {
            w.Line("AddSummary(" + self + ", " + Literal(type.TypeDoc) + ");");
        }

        var methodIndex = 0;
        foreach (var member in type.Members)
        {
            switch (member.Kind)
            {
                case "Field":
                    w.Line("AddSummary(" + self + ".GetField(" + Literal(member.Name) + ", Flags), " + Literal(member.Text!) + ");");
                    break;
                case "Property":
                    w.Line("AddSummary(" + self + ".GetProperty(" + Literal(member.Name) + ", Flags), " + Literal(member.Text!) + ");");
                    break;
                default:
                    var local = "m" + methodIndex++;
                    var types = string.Join(", ", member.ParameterTypes);
                    w.Line("var " + local + " = " + self + ".GetMethod(" + Literal(member.Name) + ", Flags, null, new global::System.Type[] { " + types + " }, null);");
                    if (member.Text is not null)
                    {
                        w.Line("AddSummary(" + local + ", " + Literal(member.Text) + ");");
                    }

                    foreach (var parameter in member.Params)
                    {
                        w.Line("AddParameter(" + local + ", " + parameter.Position + ", " + Literal(parameter.Text) + ");");
                    }

                    break;
            }
        }

        w.Close();
        w.Line();
        w.Line("public string? GetSummary(global::System.Reflection.MemberInfo member)");
        w.Open();
        w.Line("return member.Module == " + self + ".Module && _summaries.TryGetValue(member.MetadataToken, out var text) ? text : null;");
        w.Close();
        w.Line();
        w.Line("public string? GetParameterSummary(global::System.Reflection.ParameterInfo parameter)");
        w.Open();
        w.Line("return parameter.Member.Module == " + self + ".Module && _parameters.TryGetValue((parameter.Member.MetadataToken, parameter.Position), out var text) ? text : null;");
        w.Close();
        w.Line();
        w.Line("private void AddSummary(global::System.Reflection.MemberInfo? member, string text)");
        w.Open();
        w.Line("if (member is not null)");
        w.Open();
        w.Line("_summaries[member.MetadataToken] = text;");
        w.Close();
        w.Close();
        w.Line();
        w.Line("private void AddParameter(global::System.Reflection.MethodInfo? method, int position, string text)");
        w.Open();
        w.Line("if (method is not null)");
        w.Open();
        w.Line("_parameters[(method.MetadataToken, position)] = text;");
        w.Close();
        w.Close();
        w.Close();
    }
}
